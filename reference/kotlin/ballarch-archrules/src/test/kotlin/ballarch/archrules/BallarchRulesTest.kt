package ballarch.archrules

import com.tngtech.archunit.core.domain.JavaClasses
import com.tngtech.archunit.core.importer.ClassFileImporter
import com.tngtech.archunit.core.importer.ImportOption
import com.tngtech.archunit.lang.ArchRule
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Each seeded fixture must be caught by the rule meant for it (and the clean
 * fixture and the real examples by none). The detection matrix is written to
 * `archrules-detection.md` in the directory selected by `ballarch.results`.
 */
class BallarchRulesTest {
    private val importer = ClassFileImporter().withImportOption(ImportOption { true })
    private fun load(pkg: String): JavaClasses = importer.importPackages(pkg)

    private fun violations(rule: ArchRule, classes: JavaClasses): Int =
        rule.evaluate(classes).failureReport.details.size

    private val fixtures = linkedMapOf(
        "clean (control)" to "ballarch.archrules.fixtures.clean",
        "reads System.currentTimeMillis" to "ballarch.archrules.fixtures.clock",
        "uses kotlin.random.Random" to "ballarch.archrules.fixtures.random",
        "reads a file (java.io)" to "ballarch.archrules.fixtures.io",
        "calls Thread.sleep" to "ballarch.archrules.fixtures.thread",
        "uses ballarch.runtime" to "ballarch.archrules.fixtures.runtimeuse",
        "calls Instant.now()" to "ballarch.archrules.fixtures.javatime",
        "top-level var (global state)" to "ballarch.archrules.fixtures.globalstate",
        "var property in state" to "ballarch.archrules.fixtures.varstate",
        "MutableList in state" to "ballarch.archrules.fixtures.mutablecollection",
    )

    /** Which rule each fixture is meant to trigger. */
    private val expected = mapOf(
        "reads System.currentTimeMillis" to "deciderPurity",
        "uses kotlin.random.Random" to "deciderPurity",
        "reads a file (java.io)" to "deciderPurity",
        "calls Thread.sleep" to "deciderPurity",
        "uses ballarch.runtime" to "deciderPurity",
        "calls Instant.now()" to "deciderPurity",
        "top-level var (global state)" to "noGlobalMutableState",
        "var property in state" to "immutableValues",
        "MutableList in state" to "immutableValues",
    )

    private fun rulesFor(classes: JavaClasses) = linkedMapOf(
        "deciderPurity" to BallarchRules.deciderPurity(classes),
        "noGlobalMutableState" to BallarchRules.noGlobalMutableState(classes),
        "immutableValues" to BallarchRules.immutableValues(classes),
    )

    @Test
    fun `every seeded violation is detected by its rule and the control passes`() {
        val rows = ArrayList<String>()
        var missed = 0
        for ((label, pkg) in fixtures) {
            // The clean control lives in the root fixtures package file.
            val classes = if (label.startsWith("clean")) load("ballarch.archrules.fixtures").that(com.tngtech.archunit.base.DescribedPredicate.describe("root fixture package") { it.packageName == "ballarch.archrules.fixtures" }) else load(pkg)
            val counts = rulesFor(classes).mapValues { (_, r) -> violations(r, classes) }
            val want = expected[label]
            val ok = if (want == null) counts.values.all { it == 0 } else counts.getValue(want) > 0
            if (!ok) missed++
            rows += "| $label | " + counts.values.joinToString(" | ") { if (it > 0) "detected ($it)" else "—" } + " | ${if (ok) "yes" else "**no**"} |"
        }
        val leak = BallarchRules.featuresUseOnlyPublicApis(
            mapOf(
                "ballarch.archrules.fixtures.featurea" to "ballarch.archrules.fixtures.featurea.api",
                "ballarch.archrules.fixtures.featureb" to "ballarch.archrules.fixtures.featureb.api",
            ),
        )
        val leakCount = violations(leak, load("ballarch.archrules.fixtures"))
        if (leakCount == 0) missed++
        rows += "| feature A uses feature B's implementation | — | — | — | ${if (leakCount > 0) "yes: featuresUseOnlyPublicApis detected ($leakCount)" else "**no**"} |"
        write(
            "# Architecture-rule detection matrix\n\n" +
                "Generated by `BallarchRulesTest` (`./gradlew :ballarch-archrules:test`). Each fixture package in " +
                "`ballarch-archrules/src/test/kotlin/ballarch/archrules/fixtures` seeds one kind of violation.\n\n" +
                "| Fixture | deciderPurity | noGlobalMutableState | immutableValues | Caught by the intended rule |\n|---|---|---|---|---|\n" +
                rows.joinToString("\n") + "\n",
        )
        assertEquals(0, missed, rows.joinToString("\n"))
    }

    @Test
    fun `the examples satisfy every rule`() {
        val examples = load("ballarch.examples")
        assertEquals(
            sortedSetOf(
                "ballarch.examples.catalog", "ballarch.examples.itinerary", "ballarch.examples.orderdraft", "ballarch.examples.placeorder",
                "ballarch.examples.shop.checkout", "ballarch.examples.shop.inventory", "ballarch.examples.shop.orders",
                "ballarch.examples.shop.payments", "ballarch.examples.trip", "ballarch.examples.tutorial",
            ),
            BallarchRules.deciderPackages(examples),
        )
        for (rule in BallarchRules.all(examples)) rule.check(examples)
        // Composition roots (`.app` packages) wire implementations together, so they are not checked.
        val features = examples.that(com.tngtech.archunit.base.DescribedPredicate.describe("outside composition roots") { !it.packageName.endsWith(".app") })
        BallarchRules.featuresUseOnlyPublicApis(
            mapOf(
                "ballarch.examples.shop.payments" to "ballarch.examples.shop.payments.api",
                "ballarch.examples.shop.inventory" to "ballarch.examples.shop.inventory.api",
                "ballarch.examples.shop.orders" to "ballarch.examples.shop.orders.api",
                "ballarch.examples.shop.checkout" to "ballarch.examples.shop.checkout.api",
                // The itinerary uses the trip only through its port.
                "ballarch.examples.trip" to "ballarch.examples.trip.api",
                "ballarch.examples.itinerary" to "ballarch.examples.itinerary.api",
            ),
        ).check(features)
    }

    @Test
    fun `the kernel depends only on the Kotlin standard library`() {
        BallarchRules.kernelIsSelfContained().check(load("ballarch.kernel"))
    }

    private fun write(text: String) {
        val dir = System.getProperty("ballarch.results") ?: return
        File(dir).mkdirs()
        File(dir, "archrules-detection.md").writeText(text)
    }
}
